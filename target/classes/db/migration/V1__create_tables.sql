-- =========================================
-- V1: estrutura inicial do Pede Aí
-- =========================================

-- Usuários (clientes e restaurante)
CREATE TABLE tb_user (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name        VARCHAR(100)  NOT NULL,
                         email       VARCHAR(150)  NOT NULL,
                         password    VARCHAR(255)  NOT NULL,
                         role        VARCHAR(20)   NOT NULL,
                         created_at  TIMESTAMP     NOT NULL,
                         CONSTRAINT uk_user_email UNIQUE (email)
);

-- Categorias do cardápio
CREATE TABLE tb_category (
                             id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name  VARCHAR(50) NOT NULL,
                             CONSTRAINT uk_category_name UNIQUE (name)
);

-- Itens do cardápio
CREATE TABLE tb_menu_item (
                              id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              name         VARCHAR(100)   NOT NULL,
                              description  VARCHAR(255),
                              price        NUMERIC(10, 2) NOT NULL,
                              available    BOOLEAN        NOT NULL DEFAULT TRUE,
                              category_id  BIGINT         NOT NULL,
                              CONSTRAINT fk_menu_item_category FOREIGN KEY (category_id) REFERENCES tb_category (id)
);

-- Pedidos
CREATE TABLE tb_order (
                          id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          status       VARCHAR(30)    NOT NULL,
                          total        NUMERIC(10, 2) NOT NULL,
                          notes        VARCHAR(255),
                          created_at   TIMESTAMP      NOT NULL,
                          updated_at   TIMESTAMP,
                          customer_id  BIGINT         NOT NULL,
                          CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES tb_user (id)
);

-- Itens de cada pedido
CREATE TABLE tb_order_item (
                               id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               quantity      INTEGER        NOT NULL,
                               unit_price    NUMERIC(10, 2) NOT NULL,
                               subtotal      NUMERIC(10, 2) NOT NULL,
                               order_id      BIGINT         NOT NULL,
                               menu_item_id  BIGINT         NOT NULL,
                               CONSTRAINT fk_order_item_order     FOREIGN KEY (order_id)     REFERENCES tb_order (id),
                               CONSTRAINT fk_order_item_menu_item FOREIGN KEY (menu_item_id) REFERENCES tb_menu_item (id),
                               CONSTRAINT uk_order_item_order_menu_item UNIQUE (order_id, menu_item_id)
);